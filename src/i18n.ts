const LOCALES: Record<Lang, string> = {
  lv: "lv-LV", en: "en-GB", ru: "ru-RU", lt: "lt-LT", et: "et-EE",
};
export const localeOf = (l: Lang) => LOCALES[l] || "lv-LV";
